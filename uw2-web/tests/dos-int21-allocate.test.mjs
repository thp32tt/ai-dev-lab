import assert from 'node:assert/strict';
import {RealMode8086} from '../web/realmode-8086.js';
import {installDosInt21} from '../web/dos-int21.js';
const make=(alloc,paras=0x1000)=>{
 const c=new RealMode8086();
 c.load(Uint8Array.of(0xcd,0x21),0,0);
 c.set16('AX',0x4800);c.set16('BX',paras);c.set16('FLAGS',0x203);
 installDosInt21(c,alloc?{allocateMemory:alloc}:{});
 return c;
};
let got=null;
const good=make(request=>{got=request;return {segment:0x3000};});
good.step();
assert.deepEqual(got,{paragraphs:0x1000});
assert.equal(good.get16('AX'),0x3000);
assert.equal(good.get16('BX'),0x1000);
assert.equal(good.flag('CF'),false);
const error=make(()=>({errorCode:8,maxAvailableParagraphs:0x777}));
error.step();
assert.equal(error.get16('AX'),8);
assert.equal(error.get16('BX'),0x777);
assert.equal(error.flag('CF'),true);
const err7=make(()=>({errorCode:7}));
err7.step();assert.equal(err7.get16('AX'),7);assert.equal(err7.flag('CF'),true);
assert.throws(()=>make().step(),/external MCB allocator/);
assert.throws(()=>make(()=>({segment:0xff00})).step(),/outside guest physical memory/);
assert.throws(()=>make(()=>({segment:0} ),0).step(),/outside guest physical memory/);
assert.throws(()=>make(()=>({errorCode:8})).step(),/available paragraph maximum/);
assert.throws(()=>make(()=>({errorCode:9})).step(),/07h or 08h/);
assert.throws(()=>make(()=>Promise.resolve({segment:0x3000})).step(),/async DOS AH48/);
assert.throws(()=>installDosInt21(new RealMode8086(),{allocateMemory:3}),/synchronous external DOS MCB/);
console.log('UW2 original OPEN DOS AH48 exact paragraph allocation and error 7/8 fail-closed regression: PASS');
