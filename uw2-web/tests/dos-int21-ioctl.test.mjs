import assert from 'node:assert/strict';
import {RealMode8086} from '../web/realmode-8086.js';
import {installDosInt21} from '../web/dos-int21.js';
const run=(reply,sub=0,options={})=>{
 const cpu=new RealMode8086();
 cpu.load(Uint8Array.of(0xcd,0x21),0,0);
 cpu.set16('AX',0x4400|sub);cpu.set16('BX',1);
 cpu.set16('DX',0x7777);cpu.set16('FLAGS',0x203);
 installDosInt21(cpu,{...options,...(reply?{getDeviceInfo:reply}:{})});
 return cpu;
};
let asked;
const ok=run(({handle})=>{asked=handle;return {deviceInfo:0x80d3};});
ok.step();assert.equal(asked,1);
assert.equal(ok.get16('DX'),0x80d3);
assert.equal(ok.flag('CF'),false);
assert.equal(ok.get16('AX'),0x4400);
const denied=run(()=>({errorCode:6}));
denied.step();assert.equal(denied.get16('AX'),6);
assert.equal(denied.flag('CF'),true);
assert.equal(denied.get16('DX'),0x7777);
assert.throws(()=>run().step(),/external handle table/);
assert.throws(()=>run(()=>({deviceInfo:0}),1).step(),/unsupported DOS IOCTL/);
const malformed=run(()=>({deviceInfo:-1}));
assert.throws(()=>malformed.step(),/DX deviceInfo must be uint16/);
assert.equal(malformed.get16('DX'),0x7777);
assert.throws(()=>run(()=>Promise.resolve({deviceInfo:0})).step(),/async DOS IOCTL/);
assert.throws(()=>installDosInt21(new RealMode8086(),{getDeviceInfo:0}),/synchronous external DOS IOCTL/);
console.log('UW2 original OPEN DOS AH44 external handle IOCTL attributes success/error/fail-closed: PASS');
